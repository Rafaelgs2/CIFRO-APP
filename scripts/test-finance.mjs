import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const testModule=join(root,'tmp','finance-test-module.mjs');
await mkdir(join(root,'tmp'),{recursive:true});
await build({absWorkingDir:root,entryPoints:['././lib/finance.ts'],bundle:true,platform:'node',format:'esm',outfile:testModule});
const {emptyState,baseTransaction,validateState,accountBalance,totals,firstInvoice,purchaseInstallments,invoice,cardUsed,dateInMonth,demoState}=await import(pathToFileURL(testModule).href);
const s=emptyState();
s.accounts=['salary','vr','investment','reserve'].map((kind,i)=>({id:kind,name:kind,kind,initial:kind==='salary'?10000:0,date:'2026-01-01',archived:false,order:i}));
const add=t=>s.transactions.push({...baseTransaction(),date:'2026-09-05',...t});
add({type:'income',accountId:'salary',categoryId:'cat-6',amount:650000,description:'Salário'});
add({type:'income',accountId:'vr',categoryId:'cat-7',amount:85000,description:'VR'});
add({type:'expense',accountId:'salary',categoryId:'cat-0',amount:180000,description:'Aluguel'});
add({type:'expense',accountId:'vr',categoryId:'cat-1',amount:20000,description:'Almoço'});
add({type:'transfer',accountId:'salary',destinationId:'investment',amount:100000,description:'Investir'});
add({type:'transfer',accountId:'salary',destinationId:'reserve',amount:50000,description:'Reservar'});
validateState(s);
assert.equal(accountBalance(s,s.accounts[0]),330000);
assert.equal(accountBalance(s,s.accounts[1]),65000);
assert.equal(totals(s,'2026-09-01','2026-09-30').income,735000);
assert.equal(totals(s,'2026-09-01','2026-09-30').expense,200000);
assert.equal(s.accounts.reduce((n,a)=>n+accountBalance(s,a),0),545000);
const c={id:'nu',name:'Nubank',institution:'Nubank',limit:800000,closing:10,due:17,initial:50000,initialMonth:'2026-09'};
s.cards.push(c);
assert.equal(firstInvoice(c,'2026-09-09'),'2026-09');assert.equal(firstInvoice(c,'2026-09-10'),'2026-10');
assert.equal(firstInvoice({...c,closing:25,due:5},'2026-12-26'),'2027-02');
assert.equal(dateInMonth('2026-02',31),'2026-02-28');assert.equal(dateInMonth('2028-02',31),'2028-02-29');
add({type:'purchase',cardId:'nu',amount:10000,installments:3,categoryId:'cat-3',description:'Compra parcelada'});
const parts=purchaseInstallments(c,s.transactions.at(-1));assert.deepEqual(parts.map(p=>p.amount),[3334,3333,3333]);assert.deepEqual(parts.map(p=>p.month),['2026-09','2026-10','2026-11']);
assert.equal(invoice(s,c,'2026-09').total,53334);assert.equal(totals(s,'2026-09-01','2026-09-30').expense,210000);
add({type:'payment',accountId:'salary',cardId:'nu',invoiceMonth:'2026-09',amount:20000,description:'Pagamento parcial'});
assert.equal(invoice(s,c,'2026-09','2026-09-12').status,'Parcialmente paga');assert.equal(invoice(s,c,'2026-09','2026-09-18').status,'Em atraso');
assert.equal(totals(s,'2026-09-01','2026-09-30').expense,210000);assert.equal(accountBalance(s,s.accounts[0]),310000);
add({type:'payment',accountId:'salary',cardId:'nu',invoiceMonth:'2026-09',amount:33334,description:'Restante da fatura'});
assert.equal(invoice(s,c,'2026-09').status,'Paga');assert.equal(cardUsed(s,c),6666);validateState(s);
const invalid=structuredClone(s);invalid.transactions.at(-1).amount++;assert.throws(()=>validateState(invalid),/pagamento supera/);
const self=structuredClone(s);self.transactions[4].destinationId='salary';assert.throws(()=>validateState(self),/contas diferentes/);
const pre=structuredClone(s);pre.transactions[0].date='2025-12-31';assert.throws(()=>validateState(pre),/saldo inicial/);
const badDate=structuredClone(s);badDate.transactions[0].date='2026-02-31';assert.throws(()=>validateState(badDate));
const removed=structuredClone(s);removed.transactions=removed.transactions.filter(t=>t.type!=='purchase');assert.throws(()=>validateState(removed),/pagamento supera/);
assert.equal(totals(s,'2026-10-01','2026-10-31').expense,0);
validateState(demoState('2026-09'));
console.log('PASS: accounts, salary/VR, transfers, no duplicate expenses, installments with exact cents, closing cycles, leap dates, payments, validation and demonstration.');
