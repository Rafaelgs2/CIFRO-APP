import {chromium} from '../.sites-runtime/qa/node_modules/playwright/index.mjs';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('outputs', {recursive:true});
const browser = await chromium.launch({channel:'msedge', headless:true});
const context = await browser.newContext({viewport:{width:390,height:844},colorScheme:'light',reducedMotion:'reduce',isMobile:true,hasTouch:true});
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const toggle = page.getByRole('switch', {name:'Modo escuro'});
const waitTheme = theme => page.waitForFunction(t => document.documentElement.classList.contains(t), theme);
async function navigate(view) {
  await page.evaluate(v => {location.hash = v;}, view);
  await page.waitForFunction(v => location.hash === '#'+v, view);
  await page.waitForTimeout(150);
}
async function checkDarkSurfaces(label) {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, label+' viewport');
  const white = await page.locator('.topbar,.sidebar,.panel,.summary-card,.account-tile,.filters-panel,.credit-panel,.finance-dialog,.form-footer,.picker-trigger,.donut>div,[data-slot="select-content"],[data-slot="dropdown-menu-content"],[data-slot="alert-dialog-content"],input:not([type="color"]),textarea').evaluateAll(els => els.filter(el => el.getClientRects().length && getComputedStyle(el).backgroundColor === 'rgb(255, 255, 255)').map(el => el.className));
  assert.deepEqual(white, [], label+' has no unthemed white surfaces');
}
async function checkForm(button) {
  await page.getByRole('button', {name:button,exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await checkDarkSurfaces(button);
  assert.equal(await page.getByRole('dialog').evaluate(el => {const r=el.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth;}),true,button+' fits');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
}
