import {chromium} from '../.sites-runtime/qa/node_modules/playwright/index.mjs';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('outputs',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,reducedMotion:'reduce',isMobile:true,hasTouch:true});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
await page.goto('http://localhost:5173/',{waitUntil:'networkidle'});
await page.screenshot({path:'outputs/mobile-empty.png',fullPage:true});
console.log('Initial UI:',(await page.locator('main').innerText()).slice(0,650));
await page.getByRole('button',{name:'Conhecer com dados de exemplo'}).click();
await page.locator('.demo-banner').waitFor();
await page.screenshot({path:'outputs/mobile-demo.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile overflow');
await page.getByRole('button',{name:'Nova despesa',exact:true}).click();
await page.getByLabel('Descrição',{exact:true}).fill('Teste mobile');
await page.getByLabel('Valor',{exact:true}).fill('25.50');
await page.getByRole('button',{name:'Salvar',exact:true}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
await page.locator('.mobile-nav').getByRole('button',{name:'Lançamentos'}).click();
await page.getByRole('textbox',{name:'Pesquisar lançamentos'}).fill('Teste mobile');
await page.getByText('Teste mobile',{exact:true}).first().waitFor();
assert.match(await page.locator('.transaction-list').innerText(),/25,50/);
await page.locator('.transaction-row').first().click();
await page.getByLabel('Descrição',{exact:true}).fill('Teste editado');
await page.getByRole('button',{name:'Salvar',exact:true}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
await page.getByRole('textbox',{name:'Pesquisar lançamentos'}).fill('Teste editado');
await page.getByText('Gerenciar exclusões').click();
await page.getByRole('button',{name:'Excluir Teste editado',exact:true}).click();
await page.getByRole('button',{name:'Cancelar',exact:true}).click();
assert.equal(await page.locator('.transaction-row').count(),1);
await page.getByRole('button',{name:'Excluir Teste editado',exact:true}).click();
await page.getByRole('button',{name:'Confirmar',exact:true}).click();
await page.getByRole('alertdialog').waitFor({state:'hidden'});
assert.equal(await page.locator('.transaction-row').count(),0);
await page.getByRole('button',{name:'Filtros',exact:true}).click();
await page.screenshot({path:'outputs/mobile-filters.png',fullPage:true});
await page.locator('.mobile-nav').getByRole('button',{name:'Planejamento'}).click();
await page.getByRole('tab',{name:'Metas',exact:true}).click();
await page.screenshot({path:'outputs/mobile-goals.png',fullPage:true});
await page.locator('.mobile-nav').getByRole('button',{name:'Perfil',exact:true}).click();
await page.getByRole('button',{name:'Meus cartões Cartões, limites e faturas'}).click();
await page.getByRole('button',{name:'Ver fatura'}).first().click();
assert.equal(await page.getByRole('dialog').evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth}),true,'dialog within mobile viewport');await page.screenshot({path:'outputs/mobile-invoice.png',fullPage:true});
await page.keyboard.press('Escape');
await page.setViewportSize({width:1440,height:1000});
await page.locator('.sidebar').getByRole('button',{name:'Início',exact:true}).click();
await page.screenshot({path:'outputs/desktop-demo.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'desktop overflow');
await page.locator('.sidebar').getByRole('button',{name:'Relatórios',exact:true}).click();
await page.screenshot({path:'outputs/desktop-reports.png',fullPage:true});
console.log('UI_ERRORS',JSON.stringify(errors));assert.deepEqual(errors,[]);
console.log('PASS: mobile dashboard, creation/edit/delete/cancel, search, filters, goals, cards, responsive desktop reports');
}finally{await browser.close()}
